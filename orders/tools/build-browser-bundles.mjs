import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function transform(source) {
  return source
    .replace(/^import\s+[^;]+;\s*$/gm, "")
    .replace(/^export\s+(?=(?:const|let|var|function|async\s+function)\b)/gm, "");
}

function bundle(files, outFile, banner) {
  const chunks = files.map((name) => {
    const full = path.join(root, "js", name);
    return `\n/* ===== ${name} ===== */\n${transform(fs.readFileSync(full, "utf8"))}`;
  });
  const output = `/* ${banner}\n * Generated by tools/build-browser-bundles.mjs.\n * Kept as a classic script so the app works when index.html is opened directly via file://.\n */\n"use strict";\n(() => {${chunks.join("\n")}\n})();\n`;
  fs.writeFileSync(path.join(root, "js", outFile), output);
}

bundle(["templates.js", "core.js", "image.js", "storage.js", "docx.js", "app.js"], "app.bundle.js", "School Order Constructor browser bundle");
bundle(["templates.js", "core.js", "image.js", "docx.js", "tests.js"], "tests.bundle.js", "School Order Constructor browser tests bundle");
console.log("Browser bundles generated.");
