import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function transform(source) {
  return source
    .replace(/^import\s+[^;]+;\s*$/gm, "")
    .replace(/^export\s+(?=(?:const|let|var|function|async\s+function)\b)/gm, "");
}

// A module that is imported but never bundled produces a bundle that parses cleanly and
// then throws ReferenceError at runtime, so the dependency list is verified before writing.
function assertDependenciesBundled(files, sources, outFile) {
  const included = new Set(files);
  const missing = new Set();
  files.forEach((name) => {
    for (const match of sources.get(name).matchAll(/^import\s[^;]*?from\s+"\.\/([\w.-]+\.js)";/gm)) {
      if (!included.has(match[1])) missing.add(`${name} -> ${match[1]}`);
    }
  });
  if (missing.size) {
    throw new Error(`${outFile}: імпортовані модулі відсутні у списку бандла: ${[...missing].join(", ")}`);
  }
}

function bundle(files, outFile, banner) {
  const sources = new Map(files.map((name) => [name, fs.readFileSync(path.join(root, "js", name), "utf8")]));
  assertDependenciesBundled(files, sources, outFile);
  const chunks = files.map((name) => `\n/* ===== ${name} ===== */\n${transform(sources.get(name))}`);
  const output = `/* ${banner}\n * Generated by tools/build-browser-bundles.mjs.\n * Kept as a classic script so the app works when index.html is opened directly via file://.\n */\n"use strict";\n(() => {${chunks.join("\n")}\n})();\n`;
  fs.writeFileSync(path.join(root, "js", outFile), output);
}

bundle(["templates.js", "core.js", "image.js", "storage.js", "registration.js", "docx.js", "app.js"], "app.bundle.js", "School Order Constructor browser bundle");
bundle(["templates.js", "core.js", "image.js", "registration.js", "docx.js", "tests.js"], "tests.bundle.js", "School Order Constructor browser tests bundle");
console.log("Browser bundles generated.");
