function completeQuest(id) {
  const q = quests.find(item => item.id === id);
  if (!q || !isUnlocked(id)) return;
  if (!questReadiness(q).ready) {
    showToast(readinessHint(q));
    return;
  }
  if (!state.completed.includes(id)) {
    state.completed.push(id);
    state.completed.sort((a, b) => a - b);
    showToast(`Монету ${id} зібрано`);
  }
  const ids = getActiveQuestIds();
  const index = ids.indexOf(id);
  const nextId = index >= 0 ? ids[index + 1] : null;
  if (nextId) {
    state.activeQuest = nextId;
    if (state.moduleFilter !== 'all') state.moduleFilter = moduleForQuest(nextId)?.id || 'all';
  }
  saveState();
  renderAllQuests();
  setTimeout(() => document.getElementById('route').scrollIntoView({behavior:'smooth', block:'start'}), 60);
}
