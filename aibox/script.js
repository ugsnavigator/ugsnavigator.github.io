function validatePromptStructure(text) {
  const source = String(text || '').replace(/\r/g, '');
  let previousIndex = -1;
  const missing = [];
  const outOfOrder = [];
  const matches = {};

  const escapeRegExp = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  for (const section of PROMPT_SECTIONS) {
    const aliases = (PROMPT_SECTION_ALIASES[section] || [section]).map(escapeRegExp).join('|');
    const pattern = new RegExp(`(^|\\n)\\s*(?:#{1,6}\\s*)?(?:\\*\\*|__)?(?:${aliases})(?:\\*\\*|__)?\\s*(?::|—|–|-)\\s*`, 'imu');
    const match = pattern.exec(source);
    const index = match ? match.index : -1;
    matches[section] = index;
    if (index === -1) missing.push(section);
    else if (index < previousIndex) outOfOrder.push(section);
    if (index !== -1) previousIndex = Math.max(previousIndex, index);
  }
  return {
    ok: missing.length === 0 && outOfOrder.length === 0,
    score: PROMPT_SECTIONS.length - missing.length,
    missing,
    outOfOrder,
    matches
  };
}
function runPromptAudit() {
  const libraryResults = promptLibrary.map(item => ({title: item.title, ...validatePromptStructure(item.text)}));
  const questResults = quests.filter(q => q.prompt).map(item => ({title: item.title, ...validatePromptStructure(item.prompt)}));
  const failures = [...libraryResults, ...questResults].filter(result => !result.ok);
  if (failures.length) console.error('Помилки структури промптів:', failures);

  if (els.catalogAudit) {
    const valid = libraryResults.filter(result => result.ok).length;
    els.catalogAudit.textContent = failures.length
      ? `Увага: ${valid}/${promptLibrary.length} промптів пройшли автоматичну перевірку структури.`
      : `✓ Автоматична перевірка: ${valid}/${promptLibrary.length} промптів містять усі 5 частин у правильному порядку.`;
    els.catalogAudit.classList.toggle('audit-error', failures.length > 0);
  }
  return failures.length === 0;
}

